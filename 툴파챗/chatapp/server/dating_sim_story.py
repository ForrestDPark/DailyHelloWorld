def _validate_generated_scenario(gen, expected_locations):
    """생성 캐시가 엔진이 기대하는 구조(요일별 3장소, 장소마다 lines +
    선택지 정확히 2개(양·음 호감도))를 갖췄는지 확인한다. 하나라도 어긋나면
    캐시를 무시하고 고정 템플릿으로 폴백한다(깨진 생성물로 게임이 죽지 않게)."""
    if not isinstance(gen, dict) or gen.get("content_version") != GENERATED_SCENARIO_VERSION:
        return False
    days = gen.get("days")
    if not isinstance(days, dict) or not days:
        return False
    for day_str in (str(d) for d in range(1, TOTAL_DAYS + 1)):
        day_data = days.get(day_str)
        if not isinstance(day_data, dict):
            return False
        day_scenes = day_data.get("scenes")
        if not isinstance(day_scenes, dict):
            return False
        for loc in expected_locations:
            scene = day_scenes.get(loc)
            if not isinstance(scene, dict):
                return False
            lines = scene.get("lines")
            choices = scene.get("choices")
            if not isinstance(lines, list) or not lines or not all(isinstance(x, str) and x.strip() for x in lines):
                return False
            if not isinstance(choices, list) or len(choices) != 2:
                return False
            if not all(isinstance(c, dict) and isinstance(c.get("text"), str) and c["text"].strip()
                       and isinstance(c.get("affection"), int) for c in choices):
                return False
            if not (choices[0]["affection"] > 0 and choices[1]["affection"] <= 0):
                return False
    return True


def load_generated_scenario(title, expected_locations):
    """작품별 AI 생성 시나리오 캐시를 읽어 검증 통과분만 돌려준다(없거나
    깨졌으면 None → 호출부가 고정 템플릿으로 폴백)."""
    path = _generated_scenario_path(title)
    if not path or not path.is_file():
        return None
    try:
        gen = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return gen if _validate_generated_scenario(gen, expected_locations) else None


def load_generated_images(title, book_id):
    """작품 이미지 에이전트 매니페스트를 안전한 URL과 관리자용 생성 이력으로 바꾼다."""
    folder = _find_library_folder(title)
    image_dir = folder / GENERATED_IMAGE_DIRNAME if folder else None
    path = image_dir / GENERATED_IMAGE_MANIFEST if image_dir else None
    if not path or not path.is_file() or not re.fullmatch(r"[0-9a-f]{20}", book_id or ""):
        return None
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    def public(filename):
        if not isinstance(filename, str) or not re.fullmatch(r"(?:portrait|scene-[0-9a-f]{12})\.png", filename):
            return None
        target = image_dir / filename
        if not target.is_file():
            return None
        # ★ 2026-09-23: "이 사진만 재생성하기" 요청으로 파일명은 그대로 두고
        # 내용만 덮어쓰는 재생성 경로가 생겼다. 파일명이 그대로면 브라우저가
        # 예전 캐시를 계속 보여줄 수 있어, 파일 mtime을 캐시 무효화 쿼리로
        # 붙인다(이 프로젝트 전반의 ?v= 캐시버스팅 관례와 같은 원리).
        return f"/api/dating-sim/books/{book_id}/images/{filename}?t={int(target.stat().st_mtime)}"
    portrait = public(manifest.get("portrait"))
    assignments = {key: url for key, filename in (manifest.get("assignments") or {}).items()
                   if (url := public(filename))}
    if not portrait and not assignments:
        return None
    def reference_public(filename):
        if not isinstance(filename, str) or not re.fullmatch(
            r"reference-[0-9a-f]{12}\.(?:jpg|jpeg|png|webp)", filename
        ):
            return None
