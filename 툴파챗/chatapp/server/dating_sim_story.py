def _vocab_situation_lines(word, template_index):
    """단어 뜻(ko)으로 상황을 분류해 (setup, reveal, 화제 복귀) 세 줄짜리
    대사를 고른다 — "이 단어 얘기해도 될까요?" 같은 플레이어 대상 질문이
    아니라, 캐릭터가 자기 하루에 실제로 있었던 구체적인 일을 들려주는
    대사다.
    ★ 2026-09-18(6차): setup이 실제 사건을 먼저 들려주고, reveal이 그
    사건에서 비롯된 말/감정으로 단어를 잇는다.
    ★ 2026-09-18(8차): reveal 뒤에 VOCAB_TRANSITION_BACK을 항상 붙여
    beat_outro로 화제를 되돌린다(위 VOCAB_TRANSITION_BACK 주석 참고).
    ★ 2026-09-18(10차): reveal이 더 이상 "{ko}라는 말이 ~와 어울린다"는
    참조형이 아니다 — 원어(ko)가 명사면 카테고리 템플릿의 reveal(단어를
    목적어 등으로 직접 쓴 문장)을 그대로 쓰고, 서술어 사전형("-다"로
    끝남)이면 활용을 억지로 바꾸지 않고 VOCAB_PREDICATE_REVEALS(사전형
    그대로 인용해 "하마터면 튀어나올 뻔했다"로 묶는 범용 문장)를 쓴다."""
    ja, reading, ko = word
    tag = f"[{ja}|{reading}]"
    ko_ilaneun = f"{ko}{'이라는' if _korean_has_batchim(ko) else '라는'}"
    particle = _korean_object_particle(ko)
    category = _classify_vocab_word(ko)
    templates = VOCAB_SITUATION_TEMPLATES.get(category, VOCAB_SITUATION_TEMPLATES["general"])
    setup, category_reveal = templates[template_index % len(templates)]
    if _korean_is_predicate_form(ko):
        reveal = VOCAB_PREDICATE_REVEALS[template_index % len(VOCAB_PREDICATE_REVEALS)]
    else:
        reveal = category_reveal
    return [
        setup,
        reveal.format(tag=tag, ko=ko, ko_ilaneun=ko_ilaneun, particle=particle),
        VOCAB_TRANSITION_BACK,
    ]


def _seven_day_scenes(location_lines, character_name_ko="소이", character_name_jp="ソイ", vocab_pool=None):
    """location_lines는 {장소: 대사} 또는 {장소: {일차: 대사}} 둘 다 받는다 —
    후자면 요일마다 다른 활동 대사가, 전자면(예: EPUB 영감 이야기의 임시
    장소 대사) 모든 요일에 같은 대사가 붙는다.

    vocab_pool을 주면(그 작품 학습카드에서 뽑은 단어 목록) 요일마다 단어
    하나가 실제로 쓰일 법한 나레이션 장면을 장면 중간에 끼워 넣는다 —
    원작 대사 문장은 절대 그대로 옮기지 않고, 새로 쓴 안전한 나레이션에
    단어(한자+읽기+뜻)만 재료로 쓴다.

    DAY_BEATS[day]의 lines는 2개(도입+질문) 이상 몇 개든 될 수 있다 —
    ★ 2026-09-17 "하루에 나누는 대화제한도 풀어버려" 요청으로 정확히 2개로
    고정하던 제약을 없앴다. 첫 줄=도입, 마지막 줄=선택지가 답하는 질문,
    그 사이는 전부 추가 대화 턴(중간 줄)으로 취급한다.

    ★ 2026-09-17 수정: "여자가갑자기이상한말하고 답변도 다이상한데" 신고 —
    이 나레이션 줄을 장면 맨 끝(scene_lines.append)에 붙였더니, 선택지가
    실제로 답하는 질문(beat_outro)이 아니라 그 뒤에 이어붙은 줄이 화면에
    마지막으로 남아 선택지와 안 맞아 보였다. beat_outro는 항상 선택지가
    답하는 문장이어야 하므로, 나레이션 줄은 그 앞(대화 중간)에 끼워 넣어
    마지막 줄은 항상 beat_outro로 남긴다.

    ★ 2026-09-18 수정: "이거 두 장면이 개연성이없어" 신고 — 1일차(방금
    처음 만난 사이)에 "残る"(남다)처럼 관계의 지속·애착을 전제하는 단어가
    나오면, "그녀가 그 말에 마음이 걸리는 듯했다"는 나레이션 자체가 마치
    플레이어가 그녀의 속마음을 이미 읽을 수 있는 것처럼 느껴져 낯선 사이
    설정과 부딪힌다. 카테고리를 아무리 다듬어도(general·memory·feeling
    등은 특히 더) 1일차엔 "아직 서로를 모르는 사이"라는 전제 자체와
    충돌하므로, 표현 나레이션은 이미 만나서 연락을 주고받는 2일차부터만
    넣는다(직전 두 신고가 전부 1일차였다는 것도 이 판단의 근거).

    ★ 2026-09-18 재수정: "참음이 왜 갑자기생각나냐고... 참음이 생각나게끔
    하는 이전장면을 넣고서 이렇게 나오던지하게해줘" 신고 — 1일차를 뺀
    뒤에도 general류 단어는 여전히 이유 없이 튀어나왔다. 표현 삽입이
    이제 (setup, reveal, 화제 복귀) 세 줄이므로(_vocab_situation_lines),
    셋 다 outro 바로 앞에 끼워 넣는다 — setup이 먼저 분위기를 깔아
    reveal의 단어가 자연스럽게 이어지게 하고, 화제 복귀 줄이 그 뒤
    beat_outro(원래 그 요일에 하려던 질문)로 다시 자연스럽게 이어지게
    한다."""
    scenes = {}
    for day, (lines, choices) in DAY_BEATS.items():
        scenes[day] = {}
        vocab_word = vocab_pool[(day - 1) % len(vocab_pool)] if vocab_pool and day != 1 else None
        beat_lines = [line.replace("ソイ", character_name_jp).replace("소이", character_name_ko) for line in lines]
        beat_intro, beat_middle, beat_outro = beat_lines[0], beat_lines[1:-1], beat_lines[-1]
        for location, day_lines in location_lines.items():
            activity = day_lines[day] if isinstance(day_lines, dict) else day_lines
            positive_score, negative_score = choice_scores(day, location, 1)
            scene_lines = (
                [activity, beat_intro, *beat_middle, beat_outro] if day == 1
                else [beat_intro, activity, *beat_middle, beat_outro]
            )
            if vocab_word:
                scene_lines[-1:-1] = _vocab_situation_lines(vocab_word, day - 1)
            scene = {"lines": scene_lines, "choices": [
                {"text": choices[0].replace("ソイ", character_name_jp).replace("소이", character_name_ko), "affection": positive_score},
                {"text": choices[1].replace("ソイ", character_name_jp).replace("소이", character_name_ko), "affection": negative_score},
            ]}
            if vocab_word:
                scene["vocab"] = {"ja": vocab_word[0], "reading": vocab_word[1], "ko": vocab_word[2]}
            scenes[day][location] = scene
    return scenes


def choice_scores(day, location_id, variant):
    """장면별로 +7~+11/-2~-6 사이의 일관된 점수를 배정한다."""
    digest = hashlib.sha256(f"score:{day}:{location_id}:{variant}".encode()).digest()
    return 7 + digest[0] % 5, -(2 + digest[1] % 5)


