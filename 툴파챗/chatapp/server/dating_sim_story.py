def _korean_is_predicate_form(word):
    """한국어 뜻(ko)이 동사·형용사 사전형("-다"로 끝남)인지 본다 — 명사는
    한국어에서 사실상 "다"로 끝나지 않으므로 안전한 구분 기준이다."""
    return len(word) > 1 and word.endswith("다")


def _classify_vocab_word(ko_gloss):
    """단어의 한국어 풀이에서 상황 카테고리를 추정한다. 못 찾으면 general로
    떨어진다(단어를 그대로 문장에 넣어도 안전한 범용 나레이션)."""
    for category, keywords in VOCAB_CATEGORY_KEYWORDS.items():
        if any(keyword in ko_gloss for keyword in keywords):
            return category
    return "general"


def _korean_has_batchim(word):
    """마지막 글자에 받침이 있는지 — "이라는"/"라는" 같은 조사를 고르는 데
    쓴다. 한글 음절이 아니면(영문·기호 등) 받침 없는 것으로 취급한다."""
    if not word:
        return False
    code = ord(word[-1])
    if 0xAC00 <= code <= 0xD7A3:
        return (code - 0xAC00) % 28 != 0
    return False


def _korean_object_particle(word):
    """받침 여부로 목적격 조사 "을"/"를"을 고른다 — household·worry·plan
    처럼 원어(ko)가 거의 항상 명사라 문장에 직접 넣을 수 있는 카테고리
    에서 쓴다."""
    return "을" if _korean_has_batchim(word) else "를"


